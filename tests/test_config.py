from __future__ import annotations

import pytest

from geass.config import load_config, user_env_path


@pytest.fixture(autouse=True)
def isolated_home(monkeypatch, tmp_path):
    """隔离真实用户目录，避免读取 ~/.geass/env.toml 影响断言。"""
    monkeypatch.setenv("GEASS_HOME", str(tmp_path / "home"))


def test_load_config_file(tmp_path):
    path = tmp_path / "config.toml"
    path.write_text(
        '[server]\nport = 9000\ntoken = "abc"\n[agent]\nmodel = "gpt-x"\n',
        encoding="utf-8",
    )
    config = load_config(path)
    assert config.server.port == 9000
    assert config.server.token == "abc"
    assert config.agent.model == "gpt-x"


def test_env_overrides(monkeypatch, tmp_path):
    path = tmp_path / "config.toml"
    path.write_text('[server]\ntoken = "file-token"\n', encoding="utf-8")
    monkeypatch.setenv("GEASS_TOKEN", "env-token")
    monkeypatch.setenv("GEASS_API_KEY", "sk-test")
    config = load_config(path)
    assert config.server.token == "env-token"
    assert config.api_key == "sk-test"


