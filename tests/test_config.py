def test_user_env_merged(monkeypatch, tmp_path):
    project = tmp_path / "config.toml"
    project.write_text('[agent]\nmodel = "gpt-x"\n', encoding="utf-8")
    home = tmp_path / "home"
    monkeypatch.setenv("GEASS_HOME", str(home))
    user_env = home / ".geass" / "env.toml"
    user_env.parent.mkdir(parents=True)
    user_env.write_text(
        '[agent]\nmodel = "deepseek-chat"\nbase_url = "https://api.deepseek.com"\n'
        'api_key = "sk-user"\n',
        encoding="utf-8",
    )
    config = load_config(project)
    assert config.agent.model == "deepseek-chat"
    assert config.agent.base_url == "https://api.deepseek.com"
    assert config.api_key == "sk-user"


